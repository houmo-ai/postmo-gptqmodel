def setup_logger(log_dir: Path, run_tag: str, level: str = "INFO") -> logging.Logger:
    """Create logger with both console and file handlers."""
    log_dir.mkdir(parents=True, exist_ok=True)
    logger = logging.getLogger(f"r1_config_qr.{run_tag}")
    logger.setLevel(getattr(logging, level.upper(), logging.INFO))
    logger.propagate = False

    formatter = logging.Formatter(
        fmt="%(asctime)s | %(levelname)s | %(message)s",
        datefmt="%Y-%m-%d %H:%M:%S",
    )

    if not logger.handlers:
        stream_handler = logging.StreamHandler(sys.stdout)
        stream_handler.setFormatter(formatter)
        logger.addHandler(stream_handler)

        file_handler = logging.FileHandler(log_dir / f"{run_tag}.log", encoding="utf-8")
        file_handler.setFormatter(formatter)
        logger.addHandler(file_handler)

    return logger


def load_json_config(config_path: Path) -> Dict[str, Any]:
    """Load and validate top-level JSON config object."""
    if not config_path.exists():
        raise FileNotFoundError(f"Config file does not exist: {config_path}")
    with config_path.open("r", encoding="utf-8") as f:
        data = json.load(f)
    if not isinstance(data, dict) or not data:
        raise ValueError("Config file must be a non-empty JSON object.")
    return data


def resolve_layer_config(
    config_file: Optional[Union[str, Path]] = None,
    config_dict: Optional[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    if config_dict is not None:
        if not isinstance(config_dict, dict) or not config_dict:
            raise ValueError("config_dict must be a non-empty dict.")
        return config_dict
    if config_file is None:
        raise ValueError("Either config_file or config_dict must be provided.")
    return load_json_config(Path(config_file))


def select_target_entry(
    layer_config: Dict[str, Any],
    target: Optional[str],
    folder: Optional[str],
) -> Tuple[str, Dict[str, Any]]:
    """Select one target config block by layer-name key or folder value."""
    if target:
        if target not in layer_config:
            raise KeyError(
                f"Target '{target}' not found in config. "
                f"Available targets: {list(layer_config.keys())}"
            )
        entry = layer_config[target]
        if not isinstance(entry, dict):
            raise ValueError(f"Config entry for target '{target}' must be an object.")
        return target, entry

    if folder:
        matched: List[Tuple[str, Dict[str, Any]]] = []
        for name, cfg in layer_config.items():
            if not isinstance(cfg, dict):
                continue
            folder_value = str(cfg.get("folder", "")).strip()
            normalized_candidates = {folder_value, f"{folder_value}_train"}
            if folder in normalized_candidates:
                matched.append((name, cfg))
        if not matched:
            raise KeyError(
                f"Folder '{folder}' does not match any config entry folder. "
                f"Available folders: {[v.get('folder', '') for v in layer_config.values()]}"
            )
        if len(matched) > 1:
            raise ValueError(
                f"Folder '{folder}' maps to multiple config entries: "
                f"{[m[0] for m in matched]}. Use --target to disambiguate."
            )
        return matched[0]

    if len(layer_config) == 1:
        name = next(iter(layer_config))
        return name, layer_config[name]

    raise ValueError(
        "Multiple config targets found. Please specify --target or --folder."
    )


def extract_and_validate_train_args(
    entry: Dict[str, Any],
    cli_args: argparse.Namespace,
) -> Dict[str, Any]:
    """Extract train_args from config, apply defaults, override by CLI, and validate."""
    raw_train_args = {}
    if "train_args" in entry:
        if not isinstance(entry["train_args"], dict):
            raise ValueError("train_args must be a JSON object.")
        raw_train_args.update(entry["train_args"])
    if "train_data" in entry and "train_data" not in raw_train_args:
        raw_train_args["train_data"] = entry["train_data"]

    normalized = {}
    for key, value in raw_train_args.items():
        key = TRAIN_ARG_ALIASES.get(key, key)
        normalized[key] = value

    unknown_keys = set(normalized) - set(DEFAULT_TRAIN_ARGS)
    if unknown_keys:
        raise ValueError(
            f"Unsupported train_args keys: {sorted(unknown_keys)}. "
            f"Allowed keys: {sorted(DEFAULT_TRAIN_ARGS.keys())}"
        )

    merged = DEFAULT_TRAIN_ARGS.copy()
    merged.update(normalized)

    cli_override_map = {
        "num_epochs": cli_args.ep,
        "train_batch_size": cli_args.bsz,
        "learning_rate": cli_args.lr,
        "momentum": cli_args.mom,
        "optimizer": cli_args.optim,
        "cos_lr": cli_args.cos_lr,
        "init_mode": cli_args.init_mode,
        "train_subset_size": cli_args.train_subset_size,
        "accumulation_steps": cli_args.accumulation_steps,
        "head_num": cli_args.head_num,
        "parallel_workers": cli_args.parallel_workers,
        "sampling_policy": cli_args.sampling_policy,
        "outlier_mix_ratio": cli_args.outlier_mix_ratio,
        "outlier_topk_ratio": cli_args.outlier_topk_ratio,
        "outlier_score_metric": cli_args.outlier_score_metric,
    }
    for key, value in cli_override_map.items():
        if value is not None:
            merged[key] = value

    missing = [k for k in REQUIRED_TRAIN_KEYS if k not in merged]
    if missing:
        raise ValueError(f"Missing required train args after merge: {missing}")

    validate_train_args(merged)
    return merged


def validate_train_args(train_args: Dict[str, Any]) -> None:
    """Strict type/range validation with explicit error messages."""

    def check_type(key: str, expected: Iterable[type]) -> None:
        value = train_args[key]
        if not isinstance(value, tuple(expected)):
            expected_names = [t.__name__ for t in expected]
            raise TypeError(
                f"Invalid type for '{key}': expected {expected_names}, "
                f"got {type(value).__name__}."
            )

    check_type("train_data", (str,))
    if train_args["train_data"] not in ALLOWED_TRAIN_MODES:
        raise ValueError(
            f"'train_data' must be one of {sorted(ALLOWED_TRAIN_MODES)}, "
            f"got '{train_args['train_data']}'."
        )

    for key in ("train_batch_size", "num_epochs", "accumulation_steps"):
        check_type(key, (int,))
        if train_args[key] <= 0:
            raise ValueError(f"'{key}' must be > 0, got {train_args[key]}.")
    check_type("num_workers", (int,))
    if train_args["num_workers"] < 0:
        raise ValueError(f"'num_workers' must be >= 0, got {train_args['num_workers']}.")

    for key in (
        "learning_rate",
        "momentum",
        "weight_decay",
        "qsr_alpha",
        "qsr_tau",
        "qsr_qmax",
        "qsr_eps",
        "loss_scale",
    ):
        check_type(key, (int, float))

    for key in ("learning_rate", "qsr_alpha", "qsr_tau", "qsr_qmax", "qsr_eps", "loss_scale"):
        if float(train_args[key]) <= 0:
            raise ValueError(f"'{key}' must be > 0, got {train_args[key]}.")

    if not (0.0 <= float(train_args["momentum"]) <= 1.0):
        raise ValueError(
            f"'momentum' must be in [0, 1], got {train_args['momentum']}."
        )
    if float(train_args["weight_decay"]) < 0:
        raise ValueError(
            f"'weight_decay' must be >= 0, got {train_args['weight_decay']}."
        )
    if not (0.0 <= float(train_args["warmup_ratio"]) <= 1.0):
        raise ValueError(
            f"'warmup_ratio' must be in [0, 1], got {train_args['warmup_ratio']}."
        )
    if not (0.0 < float(train_args["train_subset_size"]) <= 1.0):
        raise ValueError(
            f"'train_subset_size' must be in (0, 1], got {train_args['train_subset_size']}."
        )
    if train_args.get("subset_size") is not None:
        check_type("subset_size", (int, float))
        subset_size_val = train_args["subset_size"]
        if isinstance(subset_size_val, int):
            if subset_size_val <= 0:
                raise ValueError(
                    f"'subset_size' (int) must be > 0, got {subset_size_val}."
                )
        elif isinstance(subset_size_val, float):
            if not (0.0 < subset_size_val <= 1.0):
                raise ValueError(
                    f"'subset_size' (float) must be in (0, 1], got {subset_size_val}."
                )
    if train_args["optimizer"] not in ALLOWED_OPTIMIZERS:
        raise ValueError(
            f"'optimizer' must be one of {sorted(ALLOWED_OPTIMIZERS)}, "
            f"got '{train_args['optimizer']}'."
        )
    if train_args["init_mode"] not in ALLOWED_INIT_MODES:
        raise ValueError(
            f"'init_mode' must be one of {sorted(ALLOWED_INIT_MODES)}, "
            f"got '{train_args['init_mode']}'."
        )
    if not isinstance(train_args["cos_lr"], bool):
        raise TypeError(f"'cos_lr' must be bool, got {type(train_args['cos_lr']).__name__}.")
    if not isinstance(train_args["pin_memory"], bool):
        raise TypeError(
            f"'pin_memory' must be bool, got {type(train_args['pin_memory']).__name__}."
        )
    if train_args["prefetch_factor"] is not None:
        check_type("prefetch_factor", (int,))
        if train_args["prefetch_factor"] <= 0:
            raise ValueError(
                f"'prefetch_factor' must be > 0, got {train_args['prefetch_factor']}."
            )
    if train_args["head_num"] is not None:
        check_type("head_num", (int,))
        if train_args["head_num"] <= 0:
            raise ValueError(f"'head_num' must be > 0, got {train_args['head_num']}.")
    check_type("train_nsamples", (int,))
    if train_args["train_nsamples"] <= 0:
        raise ValueError(
            f"'train_nsamples' must be > 0, got {train_args['train_nsamples']}."
        )
    check_type("device", (str,))
    if train_args["device"] not in {"auto", "cpu", "cuda"}:
        raise ValueError(
            f"'device' must be one of ['auto', 'cpu', 'cuda'], got '{train_args['device']}'."
        )
    check_type("parallel_workers", (int,))
    if train_args["parallel_workers"] <= 0:
        raise ValueError(
            f"'parallel_workers' must be > 0, got {train_args['parallel_workers']}."
        )
    if "skip_eval" in train_args and not isinstance(train_args["skip_eval"], bool):
        raise TypeError(
            f"'skip_eval' must be bool, got {type(train_args['skip_eval']).__name__}."
        )
    check_type("eval_max_batches", (int,))
    if train_args["eval_max_batches"] < 0:
        raise ValueError(
            f"'eval_max_batches' must be >= 0, got {train_args['eval_max_batches']}."
        )
    check_type("sampling_policy", (str,))
    if train_args["sampling_policy"] not in ALLOWED_SAMPLING_POLICIES:
        raise ValueError(
            f"'sampling_policy' must be one of {sorted(ALLOWED_SAMPLING_POLICIES)}, "
            f"got '{train_args['sampling_policy']}'."
        )
    check_type("outlier_mix_ratio", (int, float))
    if not (0.0 <= float(train_args["outlier_mix_ratio"]) <= 1.0):
        raise ValueError(
            f"'outlier_mix_ratio' must be in [0, 1], got {train_args['outlier_mix_ratio']}."
        )
    check_type("outlier_topk_ratio", (int, float))
    if not (0.0 < float(train_args["outlier_topk_ratio"]) <= 1.0):
        raise ValueError(
            f"'outlier_topk_ratio' must be in (0, 1], got {train_args['outlier_topk_ratio']}."
        )
    check_type("outlier_score_metric", (str,))
    if train_args["outlier_score_metric"] not in ALLOWED_OUTLIER_SCORE_METRICS:
        raise ValueError(
            f"'outlier_score_metric' must be one of {sorted(ALLOWED_OUTLIER_SCORE_METRICS)}, "
            f"got '{train_args['outlier_score_metric']}'."
        )


def build_save_payload(
    rotation_dict: Dict[str, Any],
    metrics: Dict[str, Dict[str, float]],
    args: argparse.Namespace,
    target_name: str,
    entry: Dict[str, Any],
    train_args: Dict[str, Any],
    data_dir: Path,
    hidden_size: int,
) -> Dict[str, Any]:
    """Build standardized payload for serialization."""
    payload = {
        "format_version": "dicequant.rotation.v1",
        "created_at": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        "target_name": target_name,
        "folder": entry.get("folder", target_name),
        "train_mode": train_args["train_data"],
        "hidden_size": hidden_size,
        "head_num": train_args.get("head_num"),
        "data_dir": str(data_dir),
        "rotation_matrices": rotation_dict,
        "metrics": metrics,
        "train_args": train_args,
        "config_entry": entry,
        "runtime_args": vars(args),
    }
    return payload


def save_results(payload: Dict[str, Any], output_dir: Path, save_name: Optional[str]) -> Path:
    """Save payload as torch file and metadata json sidecar."""
    output_dir.mkdir(parents=True, exist_ok=True)
    if save_name:
        file_name = save_name if save_name.endswith(".pt") else f"{save_name}.pt"
    else:
        tag = datetime.now().strftime("%Y%m%d_%H%M%S")
        file_name = f"{payload['target_name']}_{payload['train_mode']}_{tag}.pt"
    save_path = output_dir / file_name
    torch.save(payload, save_path)

    # Lightweight json sidecar for quick inspection (no tensors).
    json_path = save_path.with_suffix(".json")
    json_payload = {
        k: v
        for k, v in payload.items()
        if k not in {"rotation_matrices"}
    }
    with json_path.open("w", encoding="utf-8") as f:
        json.dump(json_payload, f, ensure_ascii=False, indent=2)
    return save_path



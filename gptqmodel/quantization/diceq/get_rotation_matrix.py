def _resolve_score_metric(train_args: Dict[str, Any]) -> Optional[str]:
    """Enable per-sample score building only when outlier-mix sampling is enabled."""
    if str(train_args.get("sampling_policy", "random")) == "outlier_mix":
        return str(train_args.get("outlier_score_metric", "p99_over_median"))
    return None


def train_rotation_for_target(
    *,
    target_name: str,
    data_path: Union[str, Path],
    config_file: Optional[Union[str, Path]] = None,
    config_dict: Optional[Dict[str, Any]] = None,
    nsamples: Optional[int] = None,
    seed: int = 0,
    device: Optional[str] = None,
    model: Optional[str] = None,
    hf_token: Optional[str] = None,
    head_num: Optional[int] = None,
    log_dir: Optional[Union[str, Path]] = None,
    log_level: str = "INFO",
    output_dir: Optional[Union[str, Path]] = None,
    save_name: Optional[str] = None,
) -> Dict[str, Any]:
    """
    Pipeline接口：基于指定数据目录训练单个 target 的旋转矩阵。

    device / nsamples 优先使用函数参数;
    若为 None，则从对应 target 的 train_args 中读取。
    """
    # --- 先解析 config，获取 entry 级 train_args 以补全缺省值 ---
    layer_config = resolve_layer_config(config_file=config_file, config_dict=config_dict)
    selected_name, entry = select_target_entry(layer_config, target_name, None)
    entry_train_args = entry.get("train_args", {})

    if device is None:
        device = str(entry_train_args.get("device", DEFAULT_TRAIN_ARGS["device"]))
    if nsamples is None:
        nsamples = int(entry_train_args.get("train_nsamples", DEFAULT_TRAIN_ARGS["train_nsamples"]))

    run_tag = f"{target_name}_{datetime.now().strftime('%Y%m%d_%H%M%S')}"
    log_root = Path(log_dir) if log_dir else Path(data_path) / "_logs"
    logger = setup_logger(log_root, run_tag=run_tag, level=log_level)

    set_random_seed(seed)
    runtime_args = _build_runtime_args(
        config_file=config_file,
        target_name=target_name,
        data_path=data_path,
        nsamples=int(nsamples),
        seed=int(seed),
        device=device,
        model=model,
        hf_token=hf_token,
        head_num=head_num,
    )

    train_args = extract_and_validate_train_args(entry, runtime_args)
    data_dir = Path(data_path)
    if not data_dir.exists():
        raise FileNotFoundError(f"Data path does not exist: {data_dir}")

    device_obj = resolve_device(device)
    metas = scan_tensor_files(data_dir, nsamples=int(nsamples))
    score_metric = _resolve_score_metric(train_args)
    refs_by_layer = build_sample_refs(
        metas,
        nsamples=int(nsamples),
        seed=int(seed),
        score_metric=score_metric,
    )

    train_mode = train_args["train_data"]
    if train_mode == "all":
        rotation_dict, metrics, hidden_size = train_all_mode(
            refs_by_layer=refs_by_layer,
            target_name=selected_name,
            train_args=train_args,
            device=device_obj,
            logger=logger,
            wandb_run=None,
        )
    elif train_mode in {"layer_wise", "head_wise"}:
        rotation_dict, metrics, hidden_size = train_layer_or_head_wise_mode(
            refs_by_layer=refs_by_layer,
            target_name=selected_name,
            train_args=train_args,
            device=device_obj,
            logger=logger,
            args=runtime_args,
            wandb_run=None,
        )
    else:
        raise ValueError(f"Unsupported train mode: {train_mode}")

    payload = build_save_payload(
        rotation_dict=rotation_dict,
        metrics=metrics,
        args=runtime_args,
        target_name=selected_name,
        entry=entry,
        train_args=train_args,
        data_dir=data_dir,
        hidden_size=hidden_size,
    )
    save_path = None
    if output_dir:
        save_path = save_results(
            payload=payload,
            output_dir=Path(output_dir),
            save_name=save_name,
        )

    return {
        "target_name": selected_name,
        "train_mode": train_mode,
        "rotation": _extract_target_rotation(selected_name, rotation_dict),
        "rotation_dict": rotation_dict,
        "metrics": metrics,
        "payload": payload,
        "save_path": str(save_path) if save_path else None,
    }


def train_rotation_for_targets(
    *,
    target_to_data_path: Dict[str, Union[str, Path]],
    config_file: Optional[Union[str, Path]] = None,
    config_dict: Optional[Dict[str, Any]] = None,
    targets: Optional[List[str]] = None,
    nsamples: Optional[int] = None,
    seed: int = 0,
    device: Optional[str] = None,
    model: Optional[str] = None,
    hf_token: Optional[str] = None,
    head_num: Optional[int] = None,
    log_dir: Optional[Union[str, Path]] = None,
    log_level: str = "INFO",
    output_dir: Optional[Union[str, Path]] = None,
) -> Dict[str, Any]:
    """
    Pipeline接口：批量训练多个 target，并返回可直接供 rotation 使用的矩阵映射。

    device / nsamples 若为 None，则由各 target 的 train_args 内配置决定。
    """
    config = resolve_layer_config(config_file=config_file, config_dict=config_dict)
    selected_targets = targets if targets else [k for k, v in config.items() if isinstance(v, dict)]

    result: Dict[str, Any] = {}
    for target_name in selected_targets:
        if target_name not in target_to_data_path:
            raise KeyError(f"Missing data path for target `{target_name}`.")
        target_output_dir = Path(output_dir) / target_name if output_dir else None
        target_result = train_rotation_for_target(
            config_file=config_file,
            config_dict=config,
            target_name=target_name,
            data_path=target_to_data_path[target_name],
            nsamples=nsamples,
            seed=seed,
            device=device,
            model=model,
            hf_token=hf_token,
            head_num=head_num,
            log_dir=log_dir,
            log_level=log_level,
            output_dir=target_output_dir,
            save_name=None,
        )
        result[target_name] = target_result["rotation"]
    return result


def main() -> None:
    args = parser_gen()
    run_tag = datetime.now().strftime("%Y%m%d_%H%M%S")
    logger = setup_logger(Path(args.log_dir), run_tag=run_tag, level=args.log_level)

    logger.info("==== Rotation Training Pipeline Started ====")
    logger.info("1/6 Parse arguments and load config")
    set_random_seed(args.seed)
    device = resolve_device(args.device)

    layer_config = load_json_config(Path(args.config_file))
    target_name, entry = select_target_entry(layer_config, args.target, args.folder)
    train_args = extract_and_validate_train_args(entry, args)
    data_dir = resolve_data_dir(args, target_name, entry)

    logger.info("Selected target: %s", target_name)
    logger.info("Selected folder: %s", entry.get("folder", target_name))
    logger.info("Train mode: %s", train_args["train_data"])
    logger.info("Data dir: %s", data_dir)
    logger.info("Device: %s", device)

    logger.info("2/6 Scan and adapt dataset format")
    metas = scan_tensor_files(data_dir, nsamples=args.nsamples)
    score_metric = _resolve_score_metric(train_args)
    refs_by_layer = build_sample_refs(
        metas,
        nsamples=args.nsamples,
        seed=int(args.seed),
        score_metric=score_metric,
    )
    layer_sizes = {k: len(v) for k, v in refs_by_layer.items()}
    logger.info("Detected layers and sample refs: %s", layer_sizes)

    if args.dry_run:
        logger.info("Dry-run enabled, stopping before training.")
        return

    logger.info("3/6 Build training tasks")
    train_mode = train_args["train_data"]
    wandb_run = maybe_init_wandb(args, target_name, train_args)

    logger.info("4/6 Start model training")
    if train_mode == "all":
        rotation_dict, metrics, hidden_size = train_all_mode(
            refs_by_layer=refs_by_layer,
            target_name=target_name,
            train_args=train_args,
            device=device,
            logger=logger,
            wandb_run=wandb_run,
        )
    elif train_mode in {"layer_wise", "head_wise"}:
        rotation_dict, metrics, hidden_size = train_layer_or_head_wise_mode(
            refs_by_layer=refs_by_layer,
            target_name=target_name,
            train_args=train_args,
            device=device,
            logger=logger,
            args=args,
            wandb_run=wandb_run,
        )
    else:
        raise ValueError(f"Unsupported train mode: {train_mode}")

    logger.info("5/6 Build standardized output payload")
    payload = build_save_payload(
        rotation_dict=rotation_dict,
        metrics=metrics,
        args=args,
        target_name=target_name,
        entry=entry,
        train_args=train_args,
        data_dir=data_dir,
        hidden_size=hidden_size,
    )

    logger.info("6/6 Save results")
    save_path = save_results(payload, Path(args.output_dir), args.save_name)
    logger.info("Saved rotation payload to: %s", save_path)

    if wandb_run is not None:
        wandb_run.finish()
    logger.info("==== Rotation Training Pipeline Finished ====")


if __name__ == "__main__":
    main()

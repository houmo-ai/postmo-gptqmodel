def resolve_device(device_arg: str) -> torch.device:
    """Resolve runtime device."""
    if device_arg == "auto":
        return torch.device("cuda" if torch.cuda.is_available() else "cpu")
    if device_arg not in {"cpu", "cuda"}:
        raise ValueError(f"Unsupported device: {device_arg}")
    if device_arg == "cuda" and not torch.cuda.is_available():
        raise ValueError("CUDA requested but not available.")
    return torch.device(device_arg)


def maybe_init_wandb(
    args: argparse.Namespace,
    target_name: str,
    train_args: Dict[str, Any],
) -> Any:
    """Initialize optional wandb run."""
    if not args.wandb:
        return None
    if wandb is None:
        raise ImportError("wandb is not installed but --wandb is enabled.")
    run_name = f"{target_name}_{datetime.now().strftime('%Y%m%d_%H%M%S')}"
    return wandb.init(
        project="dicequant_rotation_train",
        name=run_name,
        config={
            "runtime_args": vars(args),
            "target_name": target_name,
            "train_args": train_args,
        },
    )


def main() -> None:
    args = parser_gen()
    run_tag = datetime.now().strftime("%Y%m%d_%H%M%S")
    logger = setup_logger(Path(args.log_dir), run_tag=run_tag, level=args.log_level)

    logger.info("==== Rotation Training Pipeline Started ====")
    logger.info("1/6 Parse arguments and load config")
    set_random_seed(args.seed)
    device = resolve_device(args.device)

    layer_config = load_json_config(Path(args.config_file))
    target_name, entry = select_target_entry(layer_config, args.target, args.folder)
    train_args = extract_and_validate_train_args(entry, args)
    data_dir = resolve_data_dir(args, target_name, entry)

    logger.info("Selected target: %s", target_name)
    logger.info("Selected folder: %s", entry.get("folder", target_name))
    logger.info("Train mode: %s", train_args["train_data"])
    logger.info("Data dir: %s", data_dir)
    logger.info("Device: %s", device)

    logger.info("2/6 Scan and adapt dataset format")
    metas = scan_tensor_files(data_dir, nsamples=args.nsamples)
    refs_by_layer = build_sample_refs(metas, nsamples=args.nsamples)
    layer_sizes = {k: len(v) for k, v in refs_by_layer.items()}
    logger.info("Detected layers and sample refs: %s", layer_sizes)

    if args.dry_run:
        logger.info("Dry-run enabled, stopping before training.")
        return

    logger.info("3/6 Build training tasks")
    train_mode = train_args["train_data"]
    wandb_run = maybe_init_wandb(args, target_name, train_args)

    logger.info("4/6 Start model training")
    if train_mode == "all":
        rotation_dict, metrics, hidden_size = train_all_mode(
            refs_by_layer=refs_by_layer,
            target_name=target_name,
            train_args=train_args,
            device=device,
            logger=logger,
            wandb_run=wandb_run,
        )
    elif train_mode in {"layer_wise", "head_wise"}:
        rotation_dict, metrics, hidden_size = train_layer_or_head_wise_mode(
            refs_by_layer=refs_by_layer,
            target_name=target_name,
            train_args=train_args,
            device=device,
            logger=logger,
            args=args,
            wandb_run=wandb_run,
        )
    else:
        raise ValueError(f"Unsupported train mode: {train_mode}")

    logger.info("5/6 Build standardized output payload")
    payload = build_save_payload(
        rotation_dict=rotation_dict,
        metrics=metrics,
        args=args,
        target_name=target_name,
        entry=entry,
        train_args=train_args,
        data_dir=data_dir,
        hidden_size=hidden_size,
    )

    logger.info("6/6 Save results")
    save_path = save_results(payload, Path(args.output_dir), args.save_name)
    logger.info("Saved rotation payload to: %s", save_path)

    if wandb_run is not None:
        wandb_run.finish()
    logger.info("==== Rotation Training Pipeline Finished ====")


if __name__ == "__main__":
    main()

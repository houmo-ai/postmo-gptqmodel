@dataclass(frozen=True)
class TensorFileMeta:
    """Metadata for a single tensor file in the training folder."""

    path: Path
    layer_idx: int
    sample_idx: Optional[int]
    format_type: str  # sample_separate | layer_combined | unknown


@dataclass(frozen=True)
class SampleRef:
    """Reference to one logical training sample."""

    path: Path
    layer_idx: int
    inner_idx: Optional[int] = None


class ActivationReferenceDataset(Dataset):
    """Lazy dataset that loads tensors by reference with lightweight caching."""

    def __init__(self, refs: List[SampleRef]):
        self.refs = refs
        self._cached_path: Optional[Path] = None
        self._cached_tensor: Optional[torch.Tensor] = None

    def __len__(self) -> int:
        return len(self.refs)

    def __getitem__(self, idx: int) -> torch.Tensor:
        ref = self.refs[idx]
        tensor = self._load_tensor(ref.path)
        sample = tensor if ref.inner_idx is None else tensor[ref.inner_idx]

        if sample.ndim == 3 and sample.shape[0] == 1:
            sample = sample.squeeze(0)
        if sample.ndim != 2:
            raise ValueError(
                f"Sample must be 2D after normalization, got {tuple(sample.shape)} "
                f"from file {ref.path}"
            )
        return sample

    def _load_tensor(self, path: Path) -> torch.Tensor:
        if self._cached_path == path and self._cached_tensor is not None:
            return self._cached_tensor
        tensor = safe_torch_load(path)
        if not torch.is_tensor(tensor):
            raise ValueError(f"Expected tensor in {path}, got {type(tensor)}")
        self._cached_path = path
        self._cached_tensor = tensor
        return tensor


class R1QR(nn.Module):
    """Global/layer-wise orthogonal rotation module (same core as r1_base_qr.py)."""

    def __init__(self, hidden_size: int, use_geoopt: bool = False):
        super().__init__()
        self.hidden_size = hidden_size
        self.use_geoopt = use_geoopt
        if use_geoopt:
            if geoopt is None:
                raise ImportError(
                    "geoopt is required for optimizer RSGD/RAdam, "
                    "but it is not installed in the current environment."
                )
            self.matrix = geoopt.ManifoldParameter(
                torch.eye(hidden_size),
                manifold=geoopt.manifolds.Stiefel(),
            )
        else:
            self.matrix = nn.Parameter(torch.eye(hidden_size))
        self.rotate = None

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        if self.use_geoopt:
            self.rotate = self.matrix
        else:
            self.rotate, _ = torch.linalg.qr(self.matrix, mode="complete")
        return torch.matmul(x, self.rotate)


class HeadWiseQR(nn.Module):
    """Per-head orthogonal rotation module (aligned with r2_base_qr.py style)."""

    def __init__(self, hidden_size: int, head_num: int, use_geoopt: bool = False):
        super().__init__()
        if hidden_size % head_num != 0:
            raise ValueError(
                f"hidden_size ({hidden_size}) must be divisible by head_num ({head_num})."
            )
        self.hidden_size = hidden_size
        self.head_num = head_num
        self.head_dim = hidden_size // head_num
        self.use_geoopt = use_geoopt

        init = torch.eye(self.head_dim).repeat(self.head_num, 1, 1)
        if use_geoopt:
            if geoopt is None:
                raise ImportError(
                    "geoopt is required for optimizer RSGD/RAdam, "
                    "but it is not installed in the current environment."
                )
            self.matrix = geoopt.ManifoldParameter(
                init,
                manifold=geoopt.manifolds.Stiefel(),
            )
        else:
            self.matrix = nn.Parameter(init)
        self.rotate = None

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        x_shape = x.shape
        x = x.reshape(-1, self.head_num, self.head_dim).transpose(0, 1)
        if self.use_geoopt:
            self.rotate = self.matrix
        else:
            self.rotate, _ = torch.linalg.qr(self.matrix)
        x = torch.matmul(x, self.rotate)
        return x.transpose(0, 1).reshape(x_shape)


def safe_torch_load(path: Path) -> torch.Tensor:
    """Load tensor from disk in a PyTorch-version compatible way."""
    try:
        return torch.load(path, map_location="cpu", weights_only=True)
    except TypeError:
        return torch.load(path, map_location="cpu")


def set_random_seed(seed: int) -> None:
    """Set random seed for reproducibility."""
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def setup_logger(log_dir: Path, run_tag: str, level: str = "INFO") -> logging.Logger:
    """Create logger with both console and file handlers."""
    log_dir.mkdir(parents=True, exist_ok=True)
    logger = logging.getLogger(f"r1_config_qr.{run_tag}")
    logger.setLevel(getattr(logging, level.upper(), logging.INFO))
    logger.propagate = False

    formatter = logging.Formatter(
        fmt="%(asctime)s | %(levelname)s | %(message)s",
        datefmt="%Y-%m-%d %H:%M:%S",
    )

    if not logger.handlers:
        stream_handler = logging.StreamHandler(sys.stdout)
        stream_handler.setFormatter(formatter)
        logger.addHandler(stream_handler)

        file_handler = logging.FileHandler(log_dir / f"{run_tag}.log", encoding="utf-8")
        file_handler.setFormatter(formatter)
        logger.addHandler(file_handler)

    return logger


def load_json_config(config_path: Path) -> Dict[str, Any]:
    """Load and validate top-level JSON config object."""
    if not config_path.exists():
        raise FileNotFoundError(f"Config file does not exist: {config_path}")
    with config_path.open("r", encoding="utf-8") as f:
        data = json.load(f)
    if not isinstance(data, dict) or not data:
        raise ValueError("Config file must be a non-empty JSON object.")
    return data


def select_target_entry(
    layer_config: Dict[str, Any],
    target: Optional[str],
    folder: Optional[str],
) -> Tuple[str, Dict[str, Any]]:
    """Select one target config block by layer-name key or folder value."""
    if target:
        if target not in layer_config:
            raise KeyError(
                f"Target '{target}' not found in config. "
                f"Available targets: {list(layer_config.keys())}"
            )
        entry = layer_config[target]
        if not isinstance(entry, dict):
            raise ValueError(f"Config entry for target '{target}' must be an object.")
        return target, entry

    if folder:
        matched: List[Tuple[str, Dict[str, Any]]] = []
        for name, cfg in layer_config.items():
            if not isinstance(cfg, dict):
                continue
            folder_value = str(cfg.get("folder", "")).strip()
            normalized_candidates = {folder_value, f"{folder_value}_train"}
            if folder in normalized_candidates:
                matched.append((name, cfg))
        if not matched:
            raise KeyError(
                f"Folder '{folder}' does not match any config entry folder. "
                f"Available folders: {[v.get('folder', '') for v in layer_config.values()]}"
            )
        if len(matched) > 1:
            raise ValueError(
                f"Folder '{folder}' maps to multiple config entries: "
                f"{[m[0] for m in matched]}. Use --target to disambiguate."
            )
        return matched[0]

    if len(layer_config) == 1:
        name = next(iter(layer_config))
        return name, layer_config[name]

    raise ValueError(
        "Multiple config targets found. Please specify --target or --folder."
    )


def extract_and_validate_train_args(
    entry: Dict[str, Any],
    cli_args: argparse.Namespace,
) -> Dict[str, Any]:
    """Extract train_args from config, apply defaults, override by CLI, and validate."""
    raw_train_args = {}
    if "train_args" in entry:
        if not isinstance(entry["train_args"], dict):
            raise ValueError("train_args must be a JSON object.")
        raw_train_args.update(entry["train_args"])
    if "train_data" in entry and "train_data" not in raw_train_args:
        raw_train_args["train_data"] = entry["train_data"]

    normalized = {}
    for key, value in raw_train_args.items():
        key = TRAIN_ARG_ALIASES.get(key, key)
        normalized[key] = value

    unknown_keys = set(normalized) - set(DEFAULT_TRAIN_ARGS)
    if unknown_keys:
        raise ValueError(
            f"Unsupported train_args keys: {sorted(unknown_keys)}. "
            f"Allowed keys: {sorted(DEFAULT_TRAIN_ARGS.keys())}"
        )

    merged = DEFAULT_TRAIN_ARGS.copy()
    merged.update(normalized)

    cli_override_map = {
        "num_epochs": cli_args.ep,
        "train_batch_size": cli_args.bsz,
        "learning_rate": cli_args.lr,
        "momentum": cli_args.mom,
        "optimizer": cli_args.optim,
        "cos_lr": cli_args.cos_lr,
        "init_mode": cli_args.init_mode,
        "train_subset_size": cli_args.train_subset_size,
        "accumulation_steps": cli_args.accumulation_steps,
        "head_num": cli_args.head_num,
    }
    for key, value in cli_override_map.items():
        if value is not None:
            merged[key] = value

    missing = [k for k in REQUIRED_TRAIN_KEYS if k not in merged]
    if missing:
        raise ValueError(f"Missing required train args after merge: {missing}")

    validate_train_args(merged)
    return merged


def validate_train_args(train_args: Dict[str, Any]) -> None:
    """Strict type/range validation with explicit error messages."""

    def check_type(key: str, expected: Iterable[type]) -> None:
        value = train_args[key]
        if not isinstance(value, tuple(expected)):
            expected_names = [t.__name__ for t in expected]
            raise TypeError(
                f"Invalid type for '{key}': expected {expected_names}, "
                f"got {type(value).__name__}."
            )

    check_type("train_data", (str,))
    if train_args["train_data"] not in ALLOWED_TRAIN_MODES:
        raise ValueError(
            f"'train_data' must be one of {sorted(ALLOWED_TRAIN_MODES)}, "
            f"got '{train_args['train_data']}'."
        )

    for key in ("train_batch_size", "num_epochs", "accumulation_steps"):
        check_type(key, (int,))
        if train_args[key] <= 0:
            raise ValueError(f"'{key}' must be > 0, got {train_args[key]}.")
    check_type("num_workers", (int,))
    if train_args["num_workers"] < 0:
        raise ValueError(f"'num_workers' must be >= 0, got {train_args['num_workers']}.")

    for key in (
        "learning_rate",
        "momentum",
        "weight_decay",
        "qsr_alpha",
        "qsr_tau",
        "qsr_qmax",
        "qsr_eps",
        "loss_scale",
    ):
        check_type(key, (int, float))

    for key in ("learning_rate", "qsr_alpha", "qsr_tau", "qsr_qmax", "qsr_eps", "loss_scale"):
        if float(train_args[key]) <= 0:
            raise ValueError(f"'{key}' must be > 0, got {train_args[key]}.")

    if not (0.0 <= float(train_args["momentum"]) <= 1.0):
        raise ValueError(
            f"'momentum' must be in [0, 1], got {train_args['momentum']}."
        )
    if float(train_args["weight_decay"]) < 0:
        raise ValueError(
            f"'weight_decay' must be >= 0, got {train_args['weight_decay']}."
        )
    if not (0.0 <= float(train_args["warmup_ratio"]) <= 1.0):
        raise ValueError(
            f"'warmup_ratio' must be in [0, 1], got {train_args['warmup_ratio']}."
        )
    if not (0.0 < float(train_args["train_subset_size"]) <= 1.0):
        raise ValueError(
            f"'train_subset_size' must be in (0, 1], got {train_args['train_subset_size']}."
        )
    if train_args["optimizer"] not in ALLOWED_OPTIMIZERS:
        raise ValueError(
            f"'optimizer' must be one of {sorted(ALLOWED_OPTIMIZERS)}, "
            f"got '{train_args['optimizer']}'."
        )
    if train_args["init_mode"] not in ALLOWED_INIT_MODES:
        raise ValueError(
            f"'init_mode' must be one of {sorted(ALLOWED_INIT_MODES)}, "
            f"got '{train_args['init_mode']}'."
        )
    if not isinstance(train_args["cos_lr"], bool):
        raise TypeError(f"'cos_lr' must be bool, got {type(train_args['cos_lr']).__name__}.")
    if not isinstance(train_args["pin_memory"], bool):
        raise TypeError(
            f"'pin_memory' must be bool, got {type(train_args['pin_memory']).__name__}."
        )
    if train_args["prefetch_factor"] is not None:
        check_type("prefetch_factor", (int,))
        if train_args["prefetch_factor"] <= 0:
            raise ValueError(
                f"'prefetch_factor' must be > 0, got {train_args['prefetch_factor']}."
            )
    if train_args["head_num"] is not None:
        check_type("head_num", (int,))
        if train_args["head_num"] <= 0:
            raise ValueError(f"'head_num' must be > 0, got {train_args['head_num']}.")


def resolve_data_dir(
    args: argparse.Namespace,
    target_name: str,
    entry: Dict[str, Any],
) -> Path:
    """Resolve concrete training-data directory from CLI or config."""
    if args.data_path:
        data_dir = Path(args.data_path)
        if not data_dir.exists():
            raise FileNotFoundError(f"--data_path does not exist: {data_dir}")
        return data_dir

    folder = str(entry.get("folder", target_name))
    if not folder:
        raise ValueError(
            f"Config entry '{target_name}' must define non-empty 'folder'."
        )
    if not args.model:
        raise ValueError("--model is required when --data_path is not provided.")

    model_name = args.model.split("/")[-1]
    base = Path(args.data_root) / f"{args.calib_dataset}_{args.calib_sample}samples" / model_name
    candidates = [base / folder, base / f"{folder}_train"]
    for candidate in candidates:
        if candidate.exists():
            return candidate
    raise FileNotFoundError(
        f"No data directory found for target '{target_name}'. Checked: {candidates}"
    )


def scan_tensor_files(data_dir: Path, nsamples: int) -> List[TensorFileMeta]:
    """Scan all .pt files and parse metadata from filenames."""
    if not data_dir.exists():
        raise FileNotFoundError(f"Data directory does not exist: {data_dir}")
    pt_files = sorted([p for p in data_dir.iterdir() if p.suffix == ".pt"])
    if not pt_files:
        raise FileNotFoundError(f"No .pt files found in {data_dir}.")

    sample_pattern = re.compile(r"sample_(\d+)_layer_(\d+)_.*\.pt$")
    layer_pattern = re.compile(r"layer_(\d+)_.*\.pt$")
    metas: List[TensorFileMeta] = []
    for path in pt_files:
        name = path.name
        sample_match = sample_pattern.match(name)
        if sample_match:
            sample_idx = int(sample_match.group(1))
            if sample_idx >= nsamples:
                continue
            layer_idx = int(sample_match.group(2))
            metas.append(
                TensorFileMeta(
                    path=path,
                    layer_idx=layer_idx,
                    sample_idx=sample_idx,
                    format_type="sample_separate",
                )
            )
            continue

        layer_match = layer_pattern.match(name)
        if layer_match:
            metas.append(
                TensorFileMeta(
                    path=path,
                    layer_idx=int(layer_match.group(1)),
                    sample_idx=None,
                    format_type="layer_combined",
                )
            )
            continue

        metas.append(
            TensorFileMeta(
                path=path,
                layer_idx=0,
                sample_idx=None,
                format_type="unknown",
            )
        )

    if not metas:
        raise ValueError(
            f"No usable files after nsamples filtering (nsamples={nsamples}) in {data_dir}."
        )
    return metas


def build_sample_refs(
    metas: List[TensorFileMeta],
    nsamples: int,
) -> Dict[int, List[SampleRef]]:
    """Convert file metadata to per-layer sample references."""
    refs_by_layer: Dict[int, List[SampleRef]] = {}
    for meta in metas:
        refs_by_layer.setdefault(meta.layer_idx, [])
        if meta.format_type == "sample_separate":
            refs_by_layer[meta.layer_idx].append(
                SampleRef(path=meta.path, layer_idx=meta.layer_idx, inner_idx=None)
            )
            continue

        tensor = safe_torch_load(meta.path)
        if not torch.is_tensor(tensor):
            raise ValueError(f"Expected tensor in {meta.path}, got {type(tensor)}")
        if tensor.ndim == 2:
            refs_by_layer[meta.layer_idx].append(
                SampleRef(path=meta.path, layer_idx=meta.layer_idx, inner_idx=None)
            )
            continue
        if tensor.ndim != 3:
            raise ValueError(
                f"Unsupported tensor rank {tensor.ndim} in {meta.path}; expected 2D or 3D."
            )
        ref_count = min(tensor.shape[0], nsamples)
        for idx in range(ref_count):
            refs_by_layer[meta.layer_idx].append(
                SampleRef(path=meta.path, layer_idx=meta.layer_idx, inner_idx=idx)
            )
    return refs_by_layer


def infer_hidden_size_from_dataset(dataset: Dataset) -> int:
    """Infer hidden size from the first sample."""
    if len(dataset) == 0:
        raise ValueError("Dataset is empty; cannot infer hidden size.")
    sample = dataset[0]
    if sample.ndim != 2:
        raise ValueError(f"Expected 2D sample, got shape {tuple(sample.shape)}.")
    hidden_size = int(sample.shape[-1])
    if hidden_size <= 0:
        raise ValueError(f"Invalid hidden size inferred: {hidden_size}")
    return hidden_size


def infer_head_num(
    args: argparse.Namespace,
    train_args: Dict[str, Any],
    hidden_size: int,
) -> int:
    """Infer head_num for head-wise mode from config, CLI, or model config."""
    if train_args.get("head_num") is not None:
        head_num = int(train_args["head_num"])
    elif args.head_num is not None:
        head_num = int(args.head_num)
    else:
        if not args.model:
            raise ValueError(
                "head_wise mode requires head_num, but --model is not provided."
            )
        if transformers is None:
            raise ImportError(
                "transformers is required to infer head_num from model config."
            )
        config = transformers.AutoConfig.from_pretrained(
            args.model,
            token=args.hf_token,
            trust_remote_code=True,
        )
        if not hasattr(config, "num_attention_heads"):
            raise ValueError(
                "Cannot infer head_num from model config: missing num_attention_heads."
            )
        head_num = int(config.num_attention_heads)

    if hidden_size % head_num != 0:
        raise ValueError(
            f"hidden_size ({hidden_size}) must be divisible by head_num ({head_num})."
        )
    return head_num


def build_optimizer(
    module: nn.Module,
    train_args: Dict[str, Any],
) -> torch.optim.Optimizer:
    """Create optimizer based on validated train args."""
    lr = float(train_args["learning_rate"])
    momentum = float(train_args["momentum"])
    weight_decay = float(train_args["weight_decay"])
    optimizer_name = train_args["optimizer"]

    if optimizer_name == "sgd":
        return torch.optim.SGD(
            module.parameters(),
            lr=lr,
            momentum=momentum,
            weight_decay=weight_decay,
        )
    if optimizer_name == "adam":
        return torch.optim.Adam(
            module.parameters(),
            lr=lr,
            weight_decay=weight_decay,
        )
    if optimizer_name == "adamw":
        return torch.optim.AdamW(
            module.parameters(),
            lr=lr,
            weight_decay=weight_decay,
        )
    if optimizer_name == "RSGD":
        if geoopt is None:
            raise ImportError("geoopt is not installed; cannot use RSGD.")
        return geoopt.optim.RiemannianSGD(
            module.parameters(),
            lr=lr,
            weight_decay=weight_decay,
            stabilize=10,
        )
    if optimizer_name == "RAdam":
        if geoopt is None:
            raise ImportError("geoopt is not installed; cannot use RAdam.")
        return geoopt.optim.RiemannianAdam(
            module.parameters(),
            lr=lr,
            weight_decay=weight_decay,
            stabilize=10,
        )
    raise NotImplementedError(f"Unsupported optimizer: {optimizer_name}")


def compute_qsr_loss(outputs: torch.Tensor, train_args: Dict[str, Any]) -> torch.Tensor:
    """Q-SR loss: keep same matrix-loss core logic as r1_base_qr.py."""
    q_max = float(train_args["qsr_qmax"])
    alpha = float(train_args["qsr_alpha"])
    tau = float(train_args["qsr_tau"])
    eps = float(train_args["qsr_eps"])
    loss_scale = float(train_args["loss_scale"])

    d = outputs.shape[-1]
    smooth_abs = (outputs.pow(2) + eps ** 2).sqrt()
    rho = outputs.norm(p=2, dim=-1, keepdim=True) + eps
    s = smooth_abs / rho

    log_d = math.log(d)
    m_alpha = (torch.logsumexp(alpha * s, dim=-1, keepdim=True) - log_d) / alpha
    tilde_a = rho * m_alpha

    t = m_alpha / (2 * q_max)
    u_gate = torch.sigmoid((t - s) / tau)
    tilde_u = u_gate.mean(dim=-1, keepdim=True)

    scale_term = tilde_a.pow(2)
    distortion_term = (1.0 / 12.0) + 0.25 * tilde_u
    return (scale_term * distortion_term).mean() * loss_scale


def create_train_dataloader(
    dataset: Dataset,
    train_args: Dict[str, Any],
    sampler: Optional[SubsetRandomSampler] = None,
) -> DataLoader:
    """Build dataloader with mode-safe worker settings."""
    kwargs: Dict[str, Any] = {
        "dataset": dataset,
        "batch_size": int(train_args["train_batch_size"]),
        "sampler": sampler,
        "shuffle": sampler is None,
    }
    num_workers = int(train_args["num_workers"])
    pin_memory = bool(train_args["pin_memory"]) and torch.cuda.is_available()
    kwargs["pin_memory"] = pin_memory

    if num_workers > 0:
        kwargs["num_workers"] = num_workers
        kwargs["prefetch_factor"] = int(train_args["prefetch_factor"])
        kwargs["persistent_workers"] = True
    else:
        kwargs["num_workers"] = 0
    return DataLoader(**kwargs)


@torch.no_grad()
def evaluate_rotation_loss(
    model: nn.Module,
    dataset: Dataset,
    hidden_size: int,
    train_args: Dict[str, Any],
    device: torch.device,
    max_batches: int = 20,
) -> float:
    """Evaluate trained rotation matrix on held-out pass over training data."""
    model.eval()
    dataloader = create_train_dataloader(dataset, train_args, sampler=None)
    losses: List[float] = []
    for batch_idx, batch_samples in enumerate(dataloader):
        batch_samples = batch_samples.to(device).float().reshape(-1, hidden_size)
        outputs = model(batch_samples)
        losses.append(float(compute_qsr_loss(outputs, train_args).item()))
        if max_batches > 0 and batch_idx + 1 >= max_batches:
            break
    if not losses:
        return float("nan")
    return float(np.mean(losses))


def get_effective_rotation(model: nn.Module) -> torch.Tensor:
    """Get orthogonal matrix used in forward pass."""
    if getattr(model, "use_geoopt", False):
        rotate = model.matrix
    else:
        rotate, _ = torch.linalg.qr(model.matrix)
    return rotate.detach().cpu()


def train_one_rotation(
    dataset: Dataset,
    hidden_size: int,
    train_args: Dict[str, Any],
    device: torch.device,
    logger: logging.Logger,
    train_name: str,
    head_num: Optional[int] = None,
    wandb_run: Any = None,
) -> Tuple[torch.Tensor, Dict[str, float]]:
    """Train one rotation module and return trained matrix + metrics."""
    use_geoopt = train_args["optimizer"] in {"RSGD", "RAdam"}
    if head_num is None:
        model = R1QR(hidden_size=hidden_size, use_geoopt=use_geoopt).to(device)
        init_r = get_orthogonal_matrix(
            hidden_size,
            train_args["init_mode"],
            device=device,
        ).float()
    else:
        model = HeadWiseQR(
            hidden_size=hidden_size,
            head_num=head_num,
            use_geoopt=use_geoopt,
        ).to(device)
        head_dim = hidden_size // head_num
        init_head = get_orthogonal_matrix(
            head_dim,
            train_args["init_mode"],
            device=device,
        ).float()
        init_r = init_head.unsqueeze(0).repeat(head_num, 1, 1)
    model.matrix.data.copy_(init_r)

    optimizer = build_optimizer(model, train_args)
    scheduler = None
    if train_args["cos_lr"]:
        scheduler = CosineAnnealingLR(
            optimizer,
            T_max=int(train_args["num_epochs"]),
            eta_min=0.0,
        )

    num_epochs = int(train_args["num_epochs"])
    accumulation_steps = int(train_args["accumulation_steps"])
    subset_ratio = float(train_args["train_subset_size"])
    subset_size = max(1, int(len(dataset) * subset_ratio))

    logger.info(
        "[%s] start training: samples=%d, subset_size=%d, epochs=%d, bsz=%d",
        train_name,
        len(dataset),
        subset_size,
        num_epochs,
        int(train_args["train_batch_size"]),
    )

    epoch_losses: List[float] = []
    for epoch in tqdm(
        range(num_epochs),
        desc=f"Epochs<{train_name}>",
        dynamic_ncols=True,
    ):
        model.train()
        indices = np.random.choice(len(dataset), size=subset_size, replace=False)
        sampler = SubsetRandomSampler(indices.tolist())
        dataloader = create_train_dataloader(dataset, train_args, sampler=sampler)

        loss_log: List[torch.Tensor] = []
        batch_bar = tqdm(
            dataloader,
            desc=f"Train<{train_name}> e{epoch + 1}/{num_epochs}",
            leave=False,
            dynamic_ncols=True,
        )
        for batch_idx, batch_samples in enumerate(batch_bar):
            batch_samples = batch_samples.to(device).float().reshape(-1, hidden_size)
            outputs = model(batch_samples)
            loss = compute_qsr_loss(outputs, train_args)
            loss = loss / accumulation_steps
            loss.backward()

            if (batch_idx + 1) % accumulation_steps == 0:
                optimizer.step()
                optimizer.zero_grad(set_to_none=True)

            loss_log.append(loss.detach())
            batch_bar.set_postfix(loss=float(loss.item()))

        if scheduler is not None:
            scheduler.step()

        mean_loss = float(torch.stack(loss_log).mean().item()) if loss_log else float("nan")
        epoch_losses.append(mean_loss)
        lr_now = optimizer.param_groups[0]["lr"]
        logger.info(
            "[%s] epoch %d/%d, loss=%.8f, lr=%.6e",
            train_name,
            epoch + 1,
            num_epochs,
            mean_loss,
            lr_now,
        )

        if wandb_run is not None:
            wandb_run.log(
                {
                    f"{train_name}/epoch": epoch + 1,
                    f"{train_name}/train_loss": mean_loss,
                    f"{train_name}/lr": lr_now,
                }
            )

    eval_loss = evaluate_rotation_loss(
        model=model,
        dataset=dataset,
        hidden_size=hidden_size,
        train_args=train_args,
        device=device,
    )
    logger.info("[%s] evaluation loss=%.8f", train_name, eval_loss)
    if wandb_run is not None:
        wandb_run.log({f"{train_name}/eval_loss": eval_loss})

    rotation = get_effective_rotation(model)
    metrics = {
        "final_train_loss": epoch_losses[-1] if epoch_losses else float("nan"),
        "eval_loss": eval_loss,
    }
    return rotation, metrics


def train_all_mode(
    refs_by_layer: Dict[int, List[SampleRef]],
    target_name: str,
    train_args: Dict[str, Any],
    device: torch.device,
    logger: logging.Logger,
    wandb_run: Any = None,
) -> Tuple[Dict[str, torch.Tensor], Dict[str, Dict[str, float]], int]:
    """Train one shared rotation matrix over all layers' activations."""
    all_refs: List[SampleRef] = []
    for layer_idx in sorted(refs_by_layer):
        all_refs.extend(refs_by_layer[layer_idx])
    dataset = ActivationReferenceDataset(all_refs)
    hidden_size = infer_hidden_size_from_dataset(dataset)
    rotation, metrics = train_one_rotation(
        dataset=dataset,
        hidden_size=hidden_size,
        train_args=train_args,
        device=device,
        logger=logger,
        train_name=target_name,
        head_num=None,
        wandb_run=wandb_run,
    )
    return {target_name: rotation}, {target_name: metrics}, hidden_size


def train_layer_or_head_wise_mode(
    refs_by_layer: Dict[int, List[SampleRef]],
    target_name: str,
    train_args: Dict[str, Any],
    device: torch.device,
    logger: logging.Logger,
    args: argparse.Namespace,
    wandb_run: Any = None,
) -> Tuple[Dict[str, Any], Dict[str, Dict[str, float]], int]:
    """Train per-layer matrices in layer-wise or head-wise mode."""
    train_mode = train_args["train_data"]
    is_head_wise = train_mode == "head_wise"
    rotation_dict: Dict[str, Any] = {}
    metrics_dict: Dict[str, Dict[str, float]] = {}

    sorted_layers = sorted(refs_by_layer)
    if not sorted_layers:
        raise ValueError("No layers found for layer/head-wise training.")

    first_dataset = ActivationReferenceDataset(refs_by_layer[sorted_layers[0]])
    hidden_size = infer_hidden_size_from_dataset(first_dataset)
    head_num = infer_head_num(args, train_args, hidden_size) if is_head_wise else None

    for layer_idx in tqdm(
        sorted_layers,
        desc=f"Layers<{target_name}>",
        dynamic_ncols=True,
    ):
        refs = refs_by_layer[layer_idx]
        if not refs:
            logger.warning("Layer %d has no refs, skipped.", layer_idx)
            continue

        dataset = ActivationReferenceDataset(refs)
        key = f"{target_name}_layer_{layer_idx}"
        rotation, metrics = train_one_rotation(
            dataset=dataset,
            hidden_size=hidden_size,
            train_args=train_args,
            device=device,
            logger=logger,
            train_name=key,
            head_num=head_num,
            wandb_run=wandb_run,
        )

        if is_head_wise:
            rotation_dict[key] = [rotation[i] for i in range(rotation.shape[0])]
        else:
            rotation_dict[key] = rotation
        metrics_dict[key] = metrics

    return rotation_dict, metrics_dict, hidden_size


def build_save_payload(
    rotation_dict: Dict[str, Any],
    metrics: Dict[str, Dict[str, float]],
    args: argparse.Namespace,
    target_name: str,
    entry: Dict[str, Any],
    train_args: Dict[str, Any],
    data_dir: Path,
    hidden_size: int,
) -> Dict[str, Any]:
    """Build standardized payload for serialization."""
    payload = {
        "format_version": "dicequant.rotation.v1",
        "created_at": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        "target_name": target_name,
        "folder": entry.get("folder", target_name),
        "train_mode": train_args["train_data"],
        "hidden_size": hidden_size,
        "head_num": train_args.get("head_num"),
        "data_dir": str(data_dir),
        "rotation_matrices": rotation_dict,
        "metrics": metrics,
        "train_args": train_args,
        "config_entry": entry,
        "runtime_args": vars(args),
    }
    return payload


def save_results(payload: Dict[str, Any], output_dir: Path, save_name: Optional[str]) -> Path:
    """Save payload as torch file and metadata json sidecar."""
    output_dir.mkdir(parents=True, exist_ok=True)
    if save_name:
        file_name = save_name if save_name.endswith(".pt") else f"{save_name}.pt"
    else:
        tag = datetime.now().strftime("%Y%m%d_%H%M%S")
        file_name = f"{payload['target_name']}_{payload['train_mode']}_{tag}.pt"
    save_path = output_dir / file_name
    torch.save(payload, save_path)

    # Lightweight json sidecar for quick inspection (no tensors).
    json_path = save_path.with_suffix(".json")
    json_payload = {
        k: v
        for k, v in payload.items()
        if k not in {"rotation_matrices"}
    }
    with json_path.open("w", encoding="utf-8") as f:
        json.dump(json_payload, f, ensure_ascii=False, indent=2)
    return save_path


